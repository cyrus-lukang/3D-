#!/usr/bin/env python3
"""生成 10 个桌面扫视规划点（弓字，姿态基本固定），写入 JSON 供回放。

点从哪来：本脚本按固定姿态 + 2 行×5 列弓字网格算出来（不读示教器）。
工作空间盒取自现场示教过的保守范围，避免跨奇异大跳。

  python3 tools/arm_plan_scan_waypoints.py
  ./tools/run_arm_play_waypoints.sh --execute
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime
from pathlib import Path


# 姿态：略低头看台面（与现场示教 p1 接近），全程固定，减少关节翻转
FIXED_RPY = (-2.85, -0.35, -0.30)

# 弓字 2 行 × 5 列（Base，米）
ROWS = [
    # (y, z, xs)
    (0.24, 0.40, [0.08, 0.16, 0.24, 0.32, 0.38]),
    (0.06, 0.38, [0.38, 0.32, 0.24, 0.16, 0.08]),
]


def build_poses() -> list[list[float]]:
    poses: list[list[float]] = []
    rx, ry, rz = FIXED_RPY
    for y, z, xs in ROWS:
        for x in xs:
            poses.append([float(x), float(y), float(z), float(rx), float(ry), float(rz)])
    assert len(poses) == 10
    return poses


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    p = argparse.ArgumentParser(
        description='Plan/regenerate 10 scan waypoints for nvblox.')
    p.add_argument(
        '--out',
        default=str(root / 'gpu_logs' / 'scan_waypoints_planned10.json'),
    )
    args = p.parse_args()

    poses = build_poses()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        'unit': 'm_rad',
        'frame': 'base_ee',
        'arm_ip': '192.168.1.18',
        'recorded_at': datetime.now().isoformat(timespec='seconds'),
        'source': 'arm_plan_scan_waypoints.py',
        'note': (
            '10-point lawnmower generated by formula: '
            f'FIXED_RPY={FIXED_RPY}, ROWS={ROWS}'
        ),
        'count': len(poses),
        'poses': [
            {'name': f'p{i + 1}', 'xyzrpy': [round(v, 6) for v in pose]}
            for i, pose in enumerate(poses)
        ],
    }
    text = json.dumps(payload, indent=2, ensure_ascii=False) + '\n'
    out.write_text(text, encoding='utf-8')
    # 故意不写 scan_waypoints_latest.json —— 那是示教录点专用，避免冲掉用户录制

    print(f'已重新生成 {len(poses)} 点 → {out}')
    print('（未改 scan_waypoints_latest.json，示教点不受影响）')
    print(f'公式: rpy={FIXED_RPY}')
    print('  行1: y=0.24 z=0.40  x=0.08→0.38')
    print('  行2: y=0.06 z=0.38  x=0.38→0.08')
    for i, pose in enumerate(poses):
        print(f'  p{i + 1}: xyz=[{pose[0]:.3f}, {pose[1]:.3f}, {pose[2]:.3f}]  '
              f'rpy=[{pose[3]:.3f}, {pose[4]:.3f}, {pose[5]:.3f}]')
    print(f'\n回放公式点: ./tools/run_arm_play_waypoints.sh --waypoints {out} --execute')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
